async def create_audio(key: str, text: str) -> Path:
    mp3 = OUT / f"{key}_georaster_arabic_voiceover.mp3"
    await edge_tts.Communicate(text, VOICE, rate="-8%", volume="+0%").save(str(mp3))
    return mp3

async def main() -> None:
    ffmpeg = imageio_ffmpeg.get_ffmpeg_exe()
    for key, text in TEXTS.items():
        audio = await create_audio(key, text)
        video = ROOT / f"{key}.mp4"
        output = OUT / f"{key}_georaster_arabic_explained.mp4"
        duration = "169.57" if key == "3" else "300.0"
        subprocess.run([
            ffmpeg, "-y", "-i", str(video), "-i", str(audio),
            "-map", "0:v:0", "-map", "1:a:0", "-c:v", "copy",
            "-c:a", "aac", "-b:a", "128k", "-af", "apad", "-t", duration,
            str(output),
        ], check=True)
        print(output)

if __name__ == "__main__":
    asyncio.run(main())
