from __future__ import annotations

import json
import math
import statistics
import time
import uuid
from typing import Any

from rasterio.warp import transform, transform_bounds, transform_geom
from shapely.geometry import shape

from ..config.building_model_catalog import BUILDING_MODEL_CATALOG, building_model_metadata
from ..errors import AIRasterError
from ..schemas.results_schemas import (
    BuildingAnalysisResult,
    BuildingProcessingMetadata,
    BuildingStatistics,
    GeoJSONFeature,
    GeoJSONFeatureCollection,
)
from .building_polygonization_service import BuildingFeature, BuildingVectorResult


class BuildingResultsService:
    """Standardize an existing stage-7 result for safe GIS/API consumption."""

    TARGET_CRS = "EPSG:4326"
    QUALITY_NOTE = (
        "Building candidates generated by the AI pipeline have not yet been validated "
        "against annotated real orthophoto reference data."
    )

    def build(
        self,
        vector_result: BuildingVectorResult,
    ) -> BuildingAnalysisResult:
        self._validate_vector_result(vector_result)
        started = time.perf_counter()
        statistics_result = self._statistics(vector_result.building_features)
        features = [
            self._api_feature(feature, source_type=vector_result.source_type)
            for feature in vector_result.building_features
        ]
        if vector_result.model_id == "hybrid_model_c_model_d":
            for feature in features:
                feature.properties.update({
                    "model_status": BUILDING_MODEL_CATALOG[vector_result.model_id]["status"],
                    "component_models": ["spacenet2_deeplab", "whu_unetplusplus_effb4"],
                    "fusion_method": "UNION",
                })
        collection = GeoJSONFeatureCollection(features=features)
        serialization_started = time.perf_counter()
        json.dumps(collection.model_dump(mode="json"), ensure_ascii=False, separators=(",", ":"))
        serialization_time_ms = (time.perf_counter() - serialization_started) * 1000.0
        wgs84_bounds = self._wgs84_bounds(vector_result.crs, vector_result.bounds)
        results_build_time_ms = (time.perf_counter() - started) * 1000.0
        model_metadata = dict(vector_result.model_metadata or {})
        if vector_result.model_id in BUILDING_MODEL_CATALOG:
            catalog = building_model_metadata(vector_result.model_id)
            model_metadata.update({key: catalog[key] for key in ("display_name", "status", "engine")})
        total_processing_time_ms = (
            float(model_metadata.get("total_processing_time_ms", 0.0)) + results_build_time_ms
            if vector_result.model_id == "hybrid_model_c_model_d" else
            float(vector_result.postprocessing_time_ms) + float(vector_result.polygonization_time_ms) + results_build_time_ms
        )
        model_metadata.update({
            "model_id": vector_result.model_id,
            "architecture": vector_result.model_architecture,
            "threshold": float(vector_result.threshold),
            "processing_time": total_processing_time_ms / 1000.0,
            "checkpoint_hash": vector_result.model_checkpoint_hash,
        })
        return BuildingAnalysisResult(
            analysis_id=f"building-analysis-{uuid.uuid4().hex}",
            raster_id=vector_result.raster_id,
            source_type=vector_result.source_type,
            source_resolution=[float(value) for value in vector_result.source_resolution],
            source_crs=vector_result.crs,
            native_bounds={key: float(value) for key, value in vector_result.bounds.items()},
            wgs84_bounds=wgs84_bounds,
            model_name=vector_result.model_name,
            model_version=vector_result.model_version,
            model_mode=vector_result.model_mode,
            model_id=vector_result.model_id,
            model_architecture=vector_result.model_architecture,
            model_checkpoint_hash=vector_result.model_checkpoint_hash,
            tile_size=vector_result.tile_size,
            preprocessing_profile=vector_result.preprocessing_profile,
            probability_threshold=float(vector_result.threshold),
            postprocessing_version=vector_result.postprocessing_version,
            polygonization_version=vector_result.polygonization_version,
            quality_mode=self._quality_mode(vector_result.source_type),
            quality_note=self.QUALITY_NOTE,
            candidate_count=vector_result.feature_count,
            statistics=statistics_result,
            feature_collection=collection,
            model_metadata=model_metadata,
            processing_metadata=BuildingProcessingMetadata(
                postprocessing_time_ms=float(vector_result.postprocessing_time_ms),
                polygonization_time_ms=float(vector_result.polygonization_time_ms),
                results_build_time_ms=results_build_time_ms,
                geojson_serialization_time_ms=serialization_time_ms,
                polygonization_config=dict(vector_result.polygonization_config),
                postprocessing_config=dict(vector_result.postprocessing_config),
                model_c_inference_time_ms=self._optional_float((vector_result.model_metadata or {}).get("processing_time_c")),
                model_d_inference_time_ms=self._optional_float((vector_result.model_metadata or {}).get("processing_time_d")),
                fusion_time_ms=self._optional_float((vector_result.model_metadata or {}).get("fusion_time")),
                total_processing_time_ms=total_processing_time_ms,
            ),
        )

    def _api_feature(self, feature: BuildingFeature, *, source_type: str | None) -> GeoJSONFeature:
        native_wkb = feature.geometry.wkb
        api_geometry = transform_geom(
            feature.crs,
            self.TARGET_CRS,
            feature.geometry.__geo_interface__,
            precision=-1,
        )
        if feature.geometry.wkb != native_wkb:
            raise AIRasterError(
                "RESULTS_NATIVE_GEOMETRY_MUTATED",
                "La geometrie native a ete modifiee pendant la reprojection.",
            )
        transformed = shape(api_geometry)
        if transformed.is_empty or not transformed.is_valid:
            raise AIRasterError(
                "RESULTS_WGS84_GEOMETRY_INVALID",
                "Une geometrie WGS84 produite est invalide.",
            )
        centroid_lon, centroid_lat = self._transform_point(
            feature.crs,
            feature.centroid_x,
            feature.centroid_y,
        )
        properties: dict[str, Any] = {
            "object_id": feature.building_id,
            "object_type": "building_candidate",
            "geometry_type": transformed.geom_type,
            "pixel_count": int(feature.pixel_count),
            "area_map_units": float(feature.area_map_units),
            "area_m2": None if feature.area_m2 is None else float(feature.area_m2),
            "perimeter_map_units": float(feature.perimeter_map_units),
            "perimeter_m": None if feature.perimeter_m is None else float(feature.perimeter_m),
            "centroid_native": {
                "x": float(feature.centroid_x),
                "y": float(feature.centroid_y),
            },
            "centroid_lon": centroid_lon,
            "centroid_lat": centroid_lat,
            "source": source_type,
            "model_name": feature.model_name,
            "model_id": feature.model_id,
            "model_architecture": feature.model_architecture,
            "model_checkpoint_hash": feature.model_checkpoint_hash,
            "preprocessing_profile": feature.preprocessing_profile,
            "tile_size": feature.tile_size,
            "model_version": feature.model_version,
            "threshold": float(feature.probability_threshold),
        }
        return GeoJSONFeature(
            id=feature.building_id,
            geometry=self._plain_json_value(api_geometry),
            properties=properties,
        )

    @staticmethod
    def _statistics(features: tuple[BuildingFeature, ...]) -> BuildingStatistics:
        count = len(features)
        areas = [float(feature.area_map_units) for feature in features]
        perimeters = [float(feature.perimeter_map_units) for feature in features]
        metric = all(feature.area_m2 is not None and feature.perimeter_m is not None for feature in features)
        metric = metric and count > 0
        areas_m2 = [float(feature.area_m2) for feature in features if feature.area_m2 is not None]
        perimeters_m = [float(feature.perimeter_m) for feature in features if feature.perimeter_m is not None]
        return BuildingStatistics(
            candidate_count=count,
            total_area_map_units=sum(areas),
            mean_area_map_units=statistics.fmean(areas) if areas else None,
            median_area_map_units=statistics.median(areas) if areas else None,
            min_area_map_units=min(areas) if areas else None,
            max_area_map_units=max(areas) if areas else None,
            total_perimeter_map_units=sum(perimeters),
            mean_perimeter_map_units=statistics.fmean(perimeters) if perimeters else None,
            total_area_m2=sum(areas_m2) if metric else None,
            mean_area_m2=statistics.fmean(areas_m2) if metric else None,
            median_area_m2=statistics.median(areas_m2) if metric else None,
            min_area_m2=min(areas_m2) if metric else None,
            max_area_m2=max(areas_m2) if metric else None,
            total_perimeter_m=sum(perimeters_m) if metric else None,
            mean_perimeter_m=statistics.fmean(perimeters_m) if metric else None,
        )

    @staticmethod
    def _optional_float(value: Any) -> float | None:
        return None if value is None else float(value)

    @classmethod
    def _transform_point(cls, source_crs: str, x: float, y: float) -> tuple[float, float]:
        longitudes, latitudes = transform(source_crs, cls.TARGET_CRS, [x], [y])
        longitude = float(longitudes[0])
        latitude = float(latitudes[0])
        if not (-180.0 <= longitude <= 180.0 and -90.0 <= latitude <= 90.0):
            raise AIRasterError("RESULTS_WGS84_INVALID", "Coordonnees WGS84 hors limites.")
        return longitude, latitude

    @classmethod
    def _wgs84_bounds(cls, source_crs: str, bounds: dict[str, float]) -> dict[str, float]:
        left, bottom, right, top = transform_bounds(
            source_crs,
            cls.TARGET_CRS,
            bounds["left"],
            bounds["bottom"],
            bounds["right"],
            bounds["top"],
            densify_pts=21,
        )
        return {"left": left, "bottom": bottom, "right": right, "top": top}

    @staticmethod
    def _quality_mode(source_type: str | None) -> str:
        normalized = (source_type or "").lower()
        if "sentinel" in normalized or normalized.startswith("gee"):
            return "integration_test"
        return "real_model_unvalidated"

    @classmethod
    def _plain_json_value(cls, value: Any) -> Any:
        if isinstance(value, dict):
            return {str(key): cls._plain_json_value(item) for key, item in value.items()}
        if isinstance(value, (list, tuple)):
            return [cls._plain_json_value(item) for item in value]
        if isinstance(value, (str, int, float, bool)) or value is None:
            return value
        if hasattr(value, "item"):
            return cls._plain_json_value(value.item())
        raise TypeError(f"Type non serialisable dans le GeoJSON: {type(value).__name__}")

    @staticmethod
    def _validate_vector_result(vector_result: BuildingVectorResult) -> None:
        if vector_result.feature_count != len(vector_result.building_features):
            raise AIRasterError("RESULTS_FEATURE_COUNT_MISMATCH", "Le nombre de candidats est incoherent.")
        identifiers = [feature.building_id for feature in vector_result.building_features]
        if len(identifiers) != len(set(identifiers)):
            raise AIRasterError("RESULTS_DUPLICATE_ID", "Les identifiants candidats doivent etre uniques.")
        if not vector_result.crs:
            raise AIRasterError("RESULTS_CRS_MISSING", "Le CRS source est obligatoire.")
        if not all(math.isfinite(value) and value > 0 for value in vector_result.source_resolution):
            raise AIRasterError("RESULTS_RESOLUTION_INVALID", "La resolution source est invalide.")
